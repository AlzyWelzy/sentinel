def main() -> None:
    seen = set()
    for d in PROVIDERS:
        assert d["type"] not in seen, d["type"]
        seen.add(d["type"])
        # A type prefix is the leaf's own first characters, never a template's output.
        for k in ("int:", "bool:", "opt:", "list:", "float:"):
            assert f'"{k}' not in json.dumps(d["request"]).replace(f': "{k}', ""), (d["type"], k)
        keys = [x["key"] for x in d["fields"]]
        assert len(keys) == len(set(keys)), d["type"]
    out = json.dumps(PROVIDERS, indent=1, ensure_ascii=False) + "\n"
    root = pathlib.Path(__file__).resolve().parent.parent
    for path in (root / "proto/notifiers.json", root / "api/app/data/notifiers.json"):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(out)
    print(f"{len(PROVIDERS)} providers")


if __name__ == "__main__":
    main()
