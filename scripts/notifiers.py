def f(key, label, secret=False, required=True, url=False, hosts=None, pattern=None,
      default=None, options=None, hint=None):  # fmt: skip
    d = {"key": key, "label": label}
    if hint:
        d["hint"] = hint
    if secret:
        d["secret"] = True
    if required:
        d["required"] = True
    if url or hosts:
        d["url"] = True
    if hosts:
        d["hosts"] = hosts
    if pattern:
        d["pattern"] = pattern
    if default is not None:
        d["default"] = default
    if options:
        d["options"] = options
    return d


def opt(key, label, **kw):
    return f(key, label, required=False, **kw)


def server(default=None, label="Server URL"):
    return f("server", label, url=True, default=default, required=default is None)


def req(url, body=None, fmt="json", method="POST", headers=None, basic=None, ok=None):
    r = {"method": method, "url": url, "format": fmt}
    if body is not None:
        r["body"] = body
    if headers:
        r["headers"] = headers
    if basic:
        r["basic_auth"] = list(basic)
    if ok:
        r["ok_path"], r["ok_values"] = ok
    return r


def p(type_, label, group, fields, request, docs=None):
    d = {"type": type_, "label": label, "group": group, "fields": fields, "request": request}
    if docs:
        d["docs"] = docs
    return d


